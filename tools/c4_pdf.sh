#!/bin/bash
# Build the campus-erp architecture report PDF (landscape A4).
#
# Pipeline:
#   c4/workspace.dsl  --(Structurizr CLI, docker)-->  PlantUML  --(PlantUML)-->  PNG   ┐
#   c4/erm/*.puml     --(gen_erm.py, tools/erm.sh)              .  --(PlantUML)-->  PNG   ├-- c4/pdf/template.tex --(tectonic)--> PDF
#                                                                                       ┘
# Output: c4/export/campus-erp-c4-model.pdf
#
# Why PlantUML and not the CLI's own PNG export: the structurizr/structurizr
# image cannot render images locally ("Exporting to PNG/SVG is not supported in
# this build" — that path needs the hosted API via --url). PlantUML is
# self-contained here: the exports have no `!include`, so they render offline.
# The ER diagrams are generated by tools/gen_erm.py (see tools/erm.sh).
#
# Nothing produced here is committed (c4/export/ is git-ignored); the sources are
# c4/workspace.dsl, c4/erm/*.puml and c4/pdf/template.tex.
#
# Usage:
#   tools/c4_pdf.sh                # export C4 + ER + build the PDF
#   tools/c4_pdf.sh --export-only  # only refresh c4/export/*.png
#   tools/c4_pdf.sh --no-export    # reuse existing PNGs, only build the PDF
#   tools/c4_pdf.sh --no-erm       # skip ER diagrams (C4 only)
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
C4="$ROOT/c4"
EXPORT="$C4/export"
TEMPLATE="$C4/pdf/template.tex"
STRUCTURIZR_IMAGE="${STRUCTURIZR_IMAGE:-structurizr/structurizr:latest}"
PLANTUML_IMAGE="${PLANTUML_IMAGE:-plantuml/plantuml:latest}"
OUT_NAME="campus-erp-c4-model"

do_export=1
do_pdf=1
do_erm=1
for arg in "$@"; do
  case "$arg" in
    --export-only) do_pdf=0 ;;
    --no-export)   do_export=0 ;;
    --no-erm)      do_erm=0 ;;
    *) echo "usage: $0 [--export-only|--no-export|--no-erm]" >&2; exit 2 ;;
  esac
done

say() { printf '%s\n' "$*"; }
die() { say "error: $*" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

[[ -f $C4/workspace.dsl ]] || die "missing $C4/workspace.dsl"
[[ -f $TEMPLATE ]] || die "missing $TEMPLATE"

# The Structurizr container reads the DSL as a non-root user; a 600 file makes the
# parser report only the bare filename. Keep it world-readable.
chmod 644 "$C4/workspace.dsl"
mkdir -p "$EXPORT"

# uid/gid mapping so files land owned by the invoking user, not root.
as_user=(--user "$(id -u):$(id -g)")

# ── 1. DSL -> PlantUML -> PNG ───────────────────────────────────────────────
if (( do_export )); then
  have docker || die "docker required to export diagrams (or pass --no-export)"
  say "== exporting C4 views to PlantUML (Structurizr) =="
  docker run --rm "${as_user[@]}" \
    -v "$C4":/w -w /w -v "$EXPORT":/out \
    "$STRUCTURIZR_IMAGE" export -w workspace.dsl -f plantuml -o /out \
    || die "structurizr export failed"

  say "== rendering C4 PlantUML -> PNG (PlantUML) =="
  shopt -s nullglob
  for puml in "$EXPORT"/structurizr-*.puml; do
    [[ $puml == *-key.puml ]] && continue      # skip the standalone legend
    docker run --rm "${as_user[@]}" -v "$EXPORT":/out \
      "$PLANTUML_IMAGE" -tpng -o /out "/out/$(basename "$puml")" \
      || die "plantuml render failed for $(basename "$puml")"
  done
fi

# ── 2. ER models -> PNG (target schema + legacy modules) ────────────────────
if (( do_erm )); then
  if (( do_export )); then
    "$ROOT/tools/erm.sh" || die "erm.sh failed"
  else
    "$ROOT/tools/erm.sh" --gen-only || die "erm.sh failed"
  fi
fi

(( do_pdf )) || { say "ok: views refreshed (PDF skipped)"; exit 0; }

mapfile -t pngs < <(find "$EXPORT" -maxdepth 1 -name 'structurizr-*.png' | sort)
(( ${#pngs[@]} )) || die "no C4 PNG views in $EXPORT (run without --no-export)"

tex_escape() { printf '%s' "$1" | sed -e 's/\\/\\textbackslash{}/g' -e 's/[&%#_]/\\&/g'; }

nice_title() {
  case "$1" in
    AsIs-Context)          echo "As-is — System Context (level 1)";;
    AsIs-Containers)       echo "As-is — Containers (level 2)";;
    AsIs-SvaComponents)    echo "As-is — HISSVA Components (level 3)";;
    Target-Context)        echo "Target — System Context (level 1)";;
    Target-Containers)     echo "Target — Containers (level 2)";;
    Target-ApiComponents)  echo "Target — API Components (level 3)";;
    *)                     printf '%s\n' "$1" | tr '_-' '  ';;
  esac
}

view_key() { local b; b="$(basename "$1" .png)"; echo "${b#structurizr-}"; }

# emit_figure <png-basename> <title> <small-note>
emit_figure() {
  local file="$1" title="$2" note="${3:-}"
  {
    printf '\\clearpage\n'
    printf '\\section{%s}\n' "$(tex_escape "$title")"
    if [[ -n $note ]]; then printf '\\noindent\\small\\color{erpgrey}%s\\par\\vspace{0.8em}\n' "$(tex_escape "$note")"; fi
    printf '\\begin{center}\n'
    printf '\\includegraphics[width=\\linewidth,height=0.84\\textheight,keepaspectratio]{%s}\n' "$file"
    printf '\\end{center}\n'
  }
}

# ── C4 fragment ─────────────────────────────────────────────────────────────
order=(AsIs-Context AsIs-Containers AsIs-SvaComponents \
       Target-Context Target-Containers Target-ApiComponents)

declare -A seen=()
c4frag="$EXPORT/.c4-figures.tex"
: > "$c4frag"
emit() { # <png path>
  local png="$1" key
  key="$(view_key "$png")"
  seen["$key"]=1
  emit_figure "$(basename "$png")" "$(nice_title "$key")" \
    "Source: c4/workspace.dsl → view ${key}. Rendered via Structurizr + PlantUML." >> "$c4frag"
}
for key in "${order[@]}"; do
  for png in "${pngs[@]}"; do
    [[ -z ${seen[$(view_key "$png")]:-} ]] || continue
    [[ "$(view_key "$png")" == "$key" ]] && emit "$png"
  done
done
for png in "${pngs[@]}"; do
  [[ -z ${seen[$(view_key "$png")]:-} ]] || continue
  emit "$png"
done

# ── ER fragment ─────────────────────────────────────────────────────────────
erfrag="$EXPORT/.er-figures.tex"
: > "$erfrag"
if (( do_erm )); then
  declare -A ertitles=(
    [target_canonical]="Target — canonical schema (declared foreign keys)"
    [legacy_sva4]="Legacy — sva4 Personal- und Stellenverwaltung"
    [legacy_mbs]="Legacy — mbs Finanz- und Sachmittelverfahren"
    [legacy_cob]="Legacy — cob Kosten- und Leistungsrechnung"
    [legacy_kbs]="Legacy — kbs Kassenbuchungssystem"
  )
  order_er=(target_canonical legacy_sva4 legacy_mbs legacy_cob legacy_kbs)
  declare -A erseen=()
  emit_er() { # <png path>
    local png="$1" base title note
    base="$(basename "$png" .png)"
    erseen["$base"]=1
    title="${ertitles[$base]:-$base}"
    if [[ $base == target_canonical ]]; then
      note="Read directly from the SQL migrations — every crow's foot is a declared FOREIGN KEY."
    else
      note="Reverse-engineered. The legacy schema declares no foreign keys; every edge is inferred from *_to_* link tables and naming. See docs/03-schema-analysis.md."
    fi
    emit_figure "$(basename "$png")" "$title" "$note" >> "$erfrag"
  }
  shopt -s nullglob
  erpngs=("$EXPORT"/target_canonical.png "$EXPORT"/legacy_*.png)
  for key in "${order_er[@]}"; do
    for png in "${erpngs[@]}"; do
      [[ -z ${erseen[$(basename "$png" .png)]:-} ]] || continue
      [[ "$(basename "$png" .png)" == "$key" ]] && emit_er "$png"
    done
  done
  for png in "${erpngs[@]}"; do
    [[ -z ${erseen[$(basename "$png" .png)]:-} ]] || continue
    emit_er "$png"
  done
fi

# ── 3. materialise the report and compile it ────────────────────────────────
tex="$EXPORT/$OUT_NAME.tex"
sed -e "/@C4DIAGRAMS@/r $c4frag" -e "/@C4DIAGRAMS@/d" \
    -e "/@ERDIAGRAMS@/r $erfrag" -e "/@ERDIAGRAMS@/d" \
    "$TEMPLATE" > "$tex"
rm -f "$c4frag" "$erfrag"

have tectonic || die "tectonic required to build the PDF (https://tectonic-typesetting.github.io)"

say "== compiling PDF (tectonic) =="
( cd "$EXPORT" && tectonic --keep-logs --outdir "$EXPORT" "$tex" ) \
  || die "tectonic failed (see $EXPORT/${OUT_NAME}.log)"

[[ -f "$EXPORT/$OUT_NAME.pdf" ]] || die "PDF was not produced"
say "ok: $EXPORT/$OUT_NAME.pdf  (${#pngs[@]} C4 view(s)$( ((do_erm)) && echo ", $(ls "$EXPORT"/target_canonical.png "$EXPORT"/legacy_*.png 2>/dev/null | wc -l) ER model(s)"))"
