#!/usr/bin/env python3
"""Generate the domain-error → machine-code table the HTTP layer answers with.

Every handler that maps a domain error to a status already names the errors it knows, in its
`statusForX` function (`errors.Is(err, kasse.ErrMandateNotActive)`). That list is the authority for
which errors a client can receive, so the machine codes are derived from it rather than maintained
beside it: a new error in a status function cannot reach a client without a code, and a code cannot
outlive the error it names.

    python3 tools/gen_domaincodes.py            # write internal/httpapi/domaincodes.go
    python3 tools/gen_domaincodes.py --check    # fail if the file is stale (CI)

The code for `kasse.ErrMandateNotActive` is `kasse.mandate_not_active`: the package, a dot, and the
error's name without its `Err` prefix in snake_case. It is stable by construction — renaming an error
renames its code, which is the point: a client branches on a code that still means what it says.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HTTPAPI = ROOT / "backend" / "internal" / "httpapi"
OUT = HTTPAPI / "domaincodes.go"

# `func statusForX(err error) int {` … up to the closing brace at column 0.
STATUS_FUNC = re.compile(r"^func statusFor\w*\(err error\) int \{\n(.*?)^\}", re.S | re.M)
# `errors.Is(err, kasse.ErrMandateNotActive)` — the package qualifier and the error's name.
ERROR_REF = re.compile(r"errors\.Is\(err,\s*([A-Za-z_]\w*)\.(Err\w+)\)")
# An import line: `"github.com/…/internal/modules/kasse"` (optionally aliased).
IMPORT = re.compile(r'^\s*(?:(\w+)\s+)?"([^"]+)"\s*$', re.M)

# A run of capitals is one word: VATType → vat_type, not v_a_t_type.
WORD = re.compile(r"[A-Z]+(?![a-z])|[A-Z][a-z0-9]*|[a-z0-9]+")


def snake(name: str) -> str:
    """ErrMandateNotActive → mandate_not_active."""
    if not name.startswith("Err"):
        raise ValueError(f"not an error name: {name}")
    return "_".join(w.lower() for w in WORD.findall(name[3:]))


def collect() -> list[tuple[str, str]]:
    """Every (package, error) a status function maps, sorted and deduplicated."""
    found: set[tuple[str, str]] = set()
    for path in sorted(HTTPAPI.glob("*.go")):
        if path.name.endswith("_test.go") or path.name == OUT.name:
            continue
        source = path.read_text(encoding="utf-8")
        for body in STATUS_FUNC.findall(source):
            for pkg, name in ERROR_REF.findall(body):
                found.add((pkg, name))
    if not found:
        raise SystemExit("gen_domaincodes: no status function maps a domain error — refusing to write an empty table")
    return sorted(found)


def import_paths() -> dict[str, str]:
    """Map a package name to its import path, from the imports the httpapi files already use."""
    paths: dict[str, str] = {}
    for path in sorted(HTTPAPI.glob("*.go")):
        if path.name.endswith("_test.go"):
            continue
        for alias, target in IMPORT.findall(path.read_text(encoding="utf-8")):
            name = alias or target.rsplit("/", 1)[-1]
            paths[name] = target
    return paths


def render(entries: list[tuple[str, str]]) -> str:
    used = sorted({pkg for pkg, _ in entries})
    paths = import_paths()
    missing = [pkg for pkg in used if pkg not in paths]
    if missing:
        raise SystemExit(f"gen_domaincodes: no import path for {', '.join(missing)}")
    # The code's prefix is the package's own name, not the alias a file happens to use: `core` is an
    # alias for core/einvoice, and a client should see `einvoice.…`, not the alias.
    def real(pkg: str) -> str:
        return paths[pkg].rsplit("/", 1)[-1]

    codes: dict[str, str] = {}
    for pkg, name in entries:
        code = f"{real(pkg)}.{snake(name)}"
        if code in codes:
            raise SystemExit(f"gen_domaincodes: {code} is claimed by both {codes[code]} and {pkg}.{name}")
        codes[code] = f"{pkg}.{name}"

    lines = [
        "// Code generated by tools/gen_domaincodes.py; DO NOT EDIT.",
        "",
        "package httpapi",
        "",
        "import (",
    ]
    for pkg in sorted(used, key=lambda p: paths[p]):
        if real(pkg) == pkg:
            lines.append(f'\t"{paths[pkg]}"')
        else:
            lines.append(f'\t{pkg} "{paths[pkg]}"')
    lines += [
        ")",
        "",
        "// domainErrorCodes is the machine code of every domain error a handler maps to a status. It is",
        "// generated from the statusForX functions, so an error a client can receive always has a code and",
        "// a code never outlives its error. A client branches on the code rather than on the message text.",
        "var domainErrorCodes = []domainCode{",
    ]
    for pkg, name in entries:
        lines.append(f'\t{{err: {pkg}.{name}, code: "{real(pkg)}.{snake(name)}"}},')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()

    wanted = render(collect())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != wanted:
            print("gen_domaincodes: internal/httpapi/domaincodes.go is stale — run `make contracts-gen`", file=sys.stderr)
            return 1
        print(f"domain codes OK ({wanted.count('{err:')} errors)")
        return 0
    OUT.write_text(wanted, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({wanted.count('{err:')} errors)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
